/**
 * Preventive Maintenance Automation Service
 * Automatically generates work orders based on maintenance plans
 */

const FREQUENCY_DAYS = {
  DAILY: 1,
  WEEKLY: 7,
  BIWEEKLY: 14,
  MONTHLY: 30,
  QUARTERLY: 90,
  SEMIANNUAL: 180,
  ANNUAL: 365,
};

/**
 * Calculate the next maintenance date based on frequency
 * @param {string} frequency - DAILY, WEEKLY, BIWEEKLY, MONTHLY, QUARTERLY, SEMIANNUAL, ANNUAL
 * @param {Date} lastDate - Last execution date or start date
 * @returns {Date} Next maintenance date
 */
export const calculateNextMaintenanceDate = (frequency, lastDate = new Date()) => {
  const days = FREQUENCY_DAYS[frequency] || 30;
  const nextDate = new Date(lastDate);
  nextDate.setDate(nextDate.getDate() + days);
  return nextDate;
};

/**
 * Check if a maintenance plan should generate an order
 * @param {Object} plan - Preventive maintenance plan
 * @returns {boolean} True if order should be generated
 */
export const shouldGenerateOrder = (plan) => {
  if (plan.status !== 'active') return false;

  const nextDate = new Date(plan.nextDate);
  const today = new Date();

  // Generate order if next date is today or in the past
  return nextDate <= today;
};

/**
 * Generate a work order from a preventive maintenance plan
 * @param {Object} plan - Preventive maintenance plan
 * @param {number} planId - Plan ID for reference
 * @returns {Object} Generated work order
 */
export const generateWorkOrderFromPlan = (plan, planId) => {
  const workOrder = {
    id: generateWorkOrderId(),
    planId: planId,
    type: 'PREVENTIVE',
    status: 'ASSIGNED',
    priority: 'MEDIUM', // Preventive is usually medium priority
    title: plan.name,
    description: `Plan de mantenimiento preventivo: ${plan.activity}`,
    assetId: plan.assetCode,
    assetName: plan.assetName,
    assetCode: plan.assetCode,
    activity: plan.activity,
    assignedTo: plan.assignedTo,
    estimatedHours: plan.estimatedHours,
    notes: plan.notes,
    createdAt: new Date().toISOString(),
    scheduledDate: plan.nextDate,
    dueDate: plan.nextDate,
    status: 'ASSIGNED',
    repeatPlan: planId,
  };

  return workOrder;
};

/**
 * Generate a unique work order ID
 * In production, this would be generated by the backend
 */
const generateWorkOrderId = () => {
  return `WO-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`;
};

/**
 * Process all active maintenance plans and generate orders for those due
 * @param {Array} plans - Array of preventive maintenance plans
 * @param {Function} onOrderGenerated - Callback when order is generated
 * @returns {Array} Array of generated work orders
 */
export const processPendingMaintenancePlans = async (plans, onOrderGenerated) => {
  const generatedOrders = [];

  for (const plan of plans) {
    if (shouldGenerateOrder(plan)) {
      const workOrder = generateWorkOrderFromPlan(plan);
      generatedOrders.push(workOrder);

      // Call callback to notify about generated order
      if (onOrderGenerated) {
        onOrderGenerated(workOrder, plan);
      }

      // Update plan's next date
      const nextDate = calculateNextMaintenanceDate(plan.frequency, new Date(plan.nextDate));
      plan.lastExecution = new Date().toISOString();
      plan.nextDate = nextDate.toISOString().split('T')[0];
    }
  }

  return generatedOrders;
};

/**
 * Get maintenance schedule for next N days
 * @param {Array} plans - Array of preventive maintenance plans
 * @param {number} daysAhead - Number of days to look ahead (default: 30)
 * @returns {Array} Upcoming maintenance tasks
 */
export const getUpcomingMaintenance = (plans, daysAhead = 30) => {
  const today = new Date();
  const endDate = new Date();
  endDate.setDate(endDate.getDate() + daysAhead);

  return plans
    .filter(plan => {
      if (plan.status !== 'active') return false;
      const nextDate = new Date(plan.nextDate);
      return nextDate >= today && nextDate <= endDate;
    })
    .sort((a, b) => new Date(a.nextDate) - new Date(b.nextDate));
};

/**
 * Get overdue maintenance
 * @param {Array} plans - Array of preventive maintenance plans
 * @returns {Array} Overdue maintenance tasks
 */
export const getOverdueMaintenance = (plans) => {
  const today = new Date();

  return plans.filter(plan => {
    if (plan.status !== 'active') return false;
    const nextDate = new Date(plan.nextDate);
    return nextDate < today;
  });
};

/**
 * Get maintenance statistics
 * @param {Array} plans - Array of preventive maintenance plans
 * @returns {Object} Statistics object
 */
export const getMaintenanceStats = (plans) => {
  const today = new Date();
  const in7Days = new Date();
  in7Days.setDate(in7Days.getDate() + 7);

  const overdue = plans.filter(p => {
    if (p.status !== 'active') return false;
    return new Date(p.nextDate) < today;
  }).length;

  const next7Days = plans.filter(p => {
    if (p.status !== 'active') return false;
    const nextDate = new Date(p.nextDate);
    return nextDate >= today && nextDate <= in7Days;
  }).length;

  const next30Days = plans.filter(p => {
    if (p.status !== 'active') return false;
    const in30Days = new Date();
    in30Days.setDate(in30Days.getDate() + 30);
    const nextDate = new Date(p.nextDate);
    return nextDate >= today && nextDate <= in30Days;
  }).length;

  return {
    total: plans.length,
    active: plans.filter(p => p.status === 'active').length,
    overdue,
    next7Days,
    next30Days,
  };
};

/**
 * Simulate automatic maintenance order generation
 * This would be called by a backend cron job or scheduler
 * For demo purposes, it can be called when needed
 */
export const simulateAutomaticGeneration = (plans) => {
  const generatedOrders = [];

  plans.forEach(plan => {
    if (shouldGenerateOrder(plan)) {
      const order = generateWorkOrderFromPlan(plan, plan.id);
      generatedOrders.push({
        ...order,
        generatedAt: new Date().toISOString(),
        notification: {
          supervisor: `Nueva orden preventiva para ${plan.assetName}`,
          technician: `Asignación: ${plan.activity}`,
        },
      });
    }
  });

  return generatedOrders;
};

export default {
  calculateNextMaintenanceDate,
  shouldGenerateOrder,
  generateWorkOrderFromPlan,
  processPendingMaintenancePlans,
  getUpcomingMaintenance,
  getOverdueMaintenance,
  getMaintenanceStats,
  simulateAutomaticGeneration,
  FREQUENCY_DAYS,
};
